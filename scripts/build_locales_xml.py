#!/usr/bin/env python3
"""Compile locales/*.xml|*.xlf into dense numeric arrays in i18n_data.lua.

Authored format is Android <resources><string name=>; XLIFF 1.2 is accepted
for CAT-tool drop-ins. Detection is by root tag. All XML I/O goes through
ElementTree so & < > in strings round-trip safely.
"""
import glob, os, re
import xml.etree.ElementTree as ET
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIR = os.path.join(BASE_DIR, "locales")
OUT_FILE = os.path.normpath(os.path.join(BASE_DIR, "..", "i18n_data.lua"))


def parse_android_xml(path):
    entries = {}
    for elem in ET.parse(path).getroot().findall("string"):
        name = elem.get("name")
        if name and elem.text is not None:
            entries[name.strip().upper()] = elem.text
    return entries


def parse_xliff(path):
    entries = {}
    for unit in ET.parse(path).getroot().iter():
        if not unit.tag.endswith("trans-unit"):
            continue
        uid = unit.get("id")
        target = None
        for child in unit:
            if child.tag.endswith("target") and child.text:
                target = child.text.strip()
            elif child.tag.endswith("source") and not target and child.text:
                target = child.text.strip()
        if uid and target:
            entries[uid.strip().upper()] = target
    return entries


def enum_key(name, used):
    key = re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_").upper() or "STR"
    if key[0].isdigit():
        key = "S_" + key
    base, i = key, 2
    while key in used:
        key = "%s_%d" % (base, i)
        i += 1
    return key


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    paths = sorted(glob.glob(os.path.join(SOURCE_DIR, "*.xml"))
                   + glob.glob(os.path.join(SOURCE_DIR, "*.xlf")))
    assert paths, "No .xml/.xlf files in %s/" % SOURCE_DIR
    langs = {}
    for p in paths:
        lang = os.path.splitext(os.path.basename(p))[0]
        root_tag = ET.parse(p).getroot().tag.lower()
        if "xliff" in root_tag:
            langs[lang] = parse_xliff(p)
        else:
            langs[lang] = parse_android_xml(p)
    en = langs.get("en", {})
    items = sorted(en.items())
    ids, enum_by_id, used = {}, {}, set()
    for idx, (name, txt) in enumerate(items, 1):
        ids[name] = idx
        enum_by_id[idx] = enum_key(name, used)
        used.add(enum_by_id[idx])
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("-- Generated by build_locales_xml.py. DO NOT EDIT DIRECTLY.\n")
        f.write("pfQuest_I18N_ENUM = {\n")
        for i in range(1, len(items) + 1):
            f.write("  %s = %d,\n" % (enum_by_id[i], i))
        f.write("}\n")
        f.write("pfQuest_I18N_en = {\n")
        for name, i in sorted(ids.items(), key=lambda kv: kv[1]):
            f.write('  [%d] = "%s", -- %s\n' % (i, esc(en[name]), name))
        f.write("}\n")
        for lang in sorted(langs):
            if lang == "en":
                continue
            f.write("pfQuest_I18N_%s = {\n" % lang)
            for name, i in sorted(ids.items(), key=lambda kv: kv[1]):
                if name in langs[lang]:
                    f.write('  [%d] = "%s", -- %s\n' % (i, esc(langs[lang][name]), name))
                else:
                    f.write("  [%d] = false, -- %s (missing)\n" % (i, name))
            f.write("}\n")
        f.write("pfQuest_I18N_STR2ID = {\n")
        for name, i in sorted(ids.items(), key=lambda kv: kv[1]):
            f.write('  ["%s"] = %d,\n' % (esc(en[name]), i))
        f.write("}\n")
    print("Compiled %d keys -> %s" % (len(ids), OUT_FILE))


if __name__ == "__main__":
    main()
