#!/usr/bin/env python3
"""Compile locales/*.json into dense numeric arrays in i18n_data.lua."""
import json, glob, os, re
SOURCE_DIR = "locales"
OUT_FILE = "i18n_data.lua"


def enum_key(path, used):
    key = re.sub(r"[^0-9A-Za-z]+", "_", path).strip("_").upper() or "STR"
    if key[0].isdigit():
        key = "S_" + key
    base, i = key, 2
    while key in used:
        key = "%s_%d" % (base, i)
        i += 1
    return key


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    paths = sorted(glob.glob(os.path.join(SOURCE_DIR, "*.json")))
    assert paths, "No .json files in %s/" % SOURCE_DIR
    langs = {}
    for p in paths:
        lang = os.path.splitext(os.path.basename(p))[0]
        with open(p, encoding="utf-8") as f:
            data = json.load(f)
        flat, stack = {}, [(data, "")]
        while stack:
            d, pre = stack.pop()
            for k, v in d.items():
                nk = (pre + "_" + k).upper() if pre else k.upper()
                if isinstance(v, dict):
                    stack.append((v, nk))
                else:
                    flat[nk] = str(v)
        langs[lang] = flat
    # canonical ids from the base locale, alphabetical, 1-based
    en = langs.get("en", {})
    items = sorted(en.items())
    ids, enum_by_id = {}, {}
    used = set()
    for idx, (nk, txt) in enumerate(items, 1):
        ids[nk] = idx
        enum_by_id[idx] = enum_key(nk, used)
        used.add(enum_by_id[idx])
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("-- Generated by build_locales.py. DO NOT EDIT DIRECTLY.\n")
        f.write("pfQuest_I18N_ENUM = {\n")
        for i in range(1, len(items) + 1):
            f.write("  %s = %d,\n" % (enum_by_id[i], i))
        f.write("}\n")
        f.write("pfQuest_I18N_en = {\n")
        for nk, i in sorted(ids.items(), key=lambda kv: kv[1]):
            f.write('  [%d] = "%s", -- %s\n' % (i, esc(en[nk]), nk))
        f.write("}\n")
        for lang in sorted(langs):
            if lang == "en":
                continue
            f.write("pfQuest_I18N_%s = {\n" % lang)
            for nk, i in sorted(ids.items(), key=lambda kv: kv[1]):
                if nk in langs[lang]:
                    f.write('  [%d] = "%s", -- %s\n' % (i, esc(langs[lang][nk]), nk))
                else:
                    f.write("  [%d] = false, -- %s (missing)\n" % (i, nk))
            f.write("}\n")
        f.write("pfQuest_I18N_STR2ID = {\n")
        for nk, i in sorted(ids.items(), key=lambda kv: kv[1]):
            f.write('  ["%s"] = %d,\n' % (esc(en[nk]), i))
        f.write("}\n")
    print("Compiled %d keys -> %s" % (len(ids), OUT_FILE))


if __name__ == "__main__":
    main()
